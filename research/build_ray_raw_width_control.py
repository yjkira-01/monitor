"""Freeze a raw-observation control with the geometric head's hidden width.

Declared before running: hidden32/embedding16, 1843 total parameters rather
than 1395 for geometry. All observations, OOF payloads, optimization, seeds,
80 epochs and deployment mask remain those of the previous raw control.
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'research/run_ray_raw_observation_control.py'
text = source.read_text(encoding='utf-8')
replacements = {
    'ray_raw_observation_control_20261016': 'ray_raw_width32_control_fixed_20261016',
    'torch.randn(17,17)': 'torch.randn(17,16)',
    'nn.Linear(46,22)': 'nn.Linear(45,32)',
    'nn.Linear(22,3)': 'nn.Linear(32,3)',
    '==1392': '==1843',
    "'parameters':1392": "'parameters':1843",
    '(len(vx),17,17)': '(len(vx),17,16)',
    'Close capacity, same OOF subjects/data/80ep/batch256/optimizer.':
        'Same hidden32 and embedding16 as geometric control; larger 1843 vs1395 parameters; same OOF subjects/data/80ep/batch256/optimizer.',
}
for before, after in replacements.items():
    assert text.count(before) == 1, (before, text.count(before))
    text = text.replace(before, after)
start = text.index('import hashlib')
text = '"""Same observations and hidden width as geometry; larger parameter budget.\n\nGenerated by build_ray_raw_width_control.py; see generation receipt.\n"""\n' + text[start:]
dest = ROOT / 'research/run_ray_raw_width32_control_fixed_20261016.py'
assert not dest.exists()
dest.write_text(text, encoding='utf-8')
receipt = {'status': 'registered_before_training',
    'question': 'Does the raw-control hidden22 bottleneck explain the geometric hidden32 advantage?',
    'control': 'raw input29 + embedding16 -> hidden32 -> output3; 1843 parameters',
    'fixed': 'Same OOF data, depth estimates, seeds, order, optimizer, 80 epochs, output cap, eligibility.',
    'analysis': 'Three-seed clean and five-condition subject-macro S, all four subjects; no selection by validation.',
    'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
    'generated_sha256': hashlib.sha256(dest.read_bytes()).hexdigest(),
    'test_subjects_used': []}
(ROOT / 'research/ray_raw_width32_fixed_generation.json').write_text(json.dumps(receipt, indent=2), encoding='utf-8')
print(json.dumps(receipt))
